def mark(col):   # bold = largest |value|, underline = second, among CI-excluding-0 cells; grey = CI includes 0
    ranked = sorted([i for i, c in enumerate(col) if c[2]], key=lambda i: -col[i][1])
    out = []
    for i, (t, mag, sig) in enumerate(col):
        if t == '--': out.append(t)
        elif not sig: out.append(f'\\textcolor{{gray}}{{{t}}}')
        elif ranked and i == ranked[0]: out.append(f'\\textbf{{{t}}}')
        elif len(ranked) > 1 and i == ranked[1]: out.append(f'\\underline{{{t}}}')
        else: out.append(t)
    return out
