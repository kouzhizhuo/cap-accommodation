def num(x):
    v = 100 * x
    if x == 0: return '0'
    r = f'{abs(v):.1f}'
    if r == '0.0': r = '<0.1'
    return ('\\ensuremath{-}' if v < 0 else '') + r

def cell(val, lo, hi, std=None):
    """-> (text, magnitude, significant)"""
    if val is None: return ('--', None, False)
    sig = lo is not None and hi is not None and (lo > 0 or hi < 0)
    t = num(val) + (f'\\std{{{num(std)}}}' if std not in (None,) and std == std else '')
    return (t, abs(val), sig)

