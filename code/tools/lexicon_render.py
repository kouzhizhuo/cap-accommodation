#!/usr/bin/env python3
"""Render notes/lexicons/<v>.md (+ <v>.json for the coder) from lexicon_evidence.py output.

Gate (lead, EXPERIMENT_PLAN §2.3): an item enters the VARIETY list iff
  (i) a dictionary (Wiktionary) sense carries a regional/variety label, and
  (ii) its authentic-corpus rate is >= 5x the genre-matched control (any configured gate pair).
Support addition (flagged): a ratio is only trusted if the authentic count is >= MIN_COUNT.
Varieties without a local authentic corpus get status VARIETY-DICT-ONLY when (i) holds.
Usage: lexicon_render.py <variety> [<variety> ...]
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LEX = ROOT / "notes" / "lexicons"
RATIO, MIN_COUNT = 5.0, 3
NAMES = {"sge": "Colloquial Singapore English (Singlish)", "aae": "African American English", "ngp": "Nigerian Pidgin",
         "sco": "Scots / Scottish English vernacular", "app": "Appalachian English", "ind": "Indian English",
         "inf": "Informal Standard English (register control)", "bre": "Standard British English (prestige standard)",
         "aus": "Standard Australian English"}
EWAVE = {"sge": "57 (Colloquial Singapore English)", "aae": "15 (Urban AAVE)", "ngp": "42 (Nigerian Pidgin)", "sco": "2 (Scottish English)",
         "app": "19 (Appalachian English)", "ind": "52 (Indian English)", "aus": "59 (Australian English)", "ire": "3 (Irish English)"}
CORPUS_DESC = {"aae_tw": "Groenwold AAVE tweets + UD-TwitterAAE aa250", "sae_tw": "Groenwold SAE translations + UD-TwitterAAE wh250",
               "coraal": "CORAAL transcripts (spoken AAL)", "nus_us": "NUS SMS, US senders", "sge": "CoSEM (SG nationality) + NUS SMS (Singapore)",
               "ind": "NUS SMS, India senders", "ngp": "UD_Naija-NSC + MAFAND pcm side", "mafand_en": "MAFAND en side (content-matched news English)"}


def status(e, has_corpus):
    dict_ok = e["wiktionary"]["found"]
    gates = [g for g in e.get("gate") or [] if g]
    trusted = [g for g in gates if g["auth_count"] >= MIN_COUNT]
    ratio_ok = any(g["ratio"] >= RATIO for g in trusted)
    if not has_corpus:
        return ("VARIETY-DICT-ONLY" if dict_ok else "DROP (no dictionary label, no corpus)"), None
    best = max(trusted, key=lambda g: g["ratio"]) if trusted else (max(gates, key=lambda g: g["ratio"]) if gates else None)
    if dict_ok and ratio_ok:
        return "VARIETY", best
    if not trusted:
        return ("CHECK (dictionary ok, too rare in corpus)" if dict_ok else "DROP (no label, too rare)"), best
    if ratio_ok:
        return "CHECK (corpus-specific, no dictionary label)", best
    # ratio < 5: diffuse slang only if the item really occurs in the control; otherwise the
    # control corpus is too small to certify a 5x ratio (smoothing floor), so it needs review.
    if best and best["ctrl_count"] >= MIN_COUNT:
        return "SLANG (diffuse: ratio < 5, attested in control)", best
    return ("CHECK (floor-limited: control too small to certify 5x)" if dict_ok else "CHECK (floor-limited, no dictionary label)"), best


def fmt_gate(g):
    if not g:
        return "n/a", "n/a", "n/a"
    return (f"{g['auth_count']} ({g['auth_per_M']}/M)", f"{g['ctrl_count']} ({g['ctrl_per_M']}/M)", f"{g['ratio']}")


def render(v):
    ev = json.loads((LEX / "_cache" / f"{v}_evidence.json").read_text())
    has_corpus = any(e.get("gate") for e in ev)
    rows, out = [], []
    for e in ev:
        st, g = status(e, has_corpus)
        w = e["wiktionary"]
        wk = (f"[{', '.join(w.get('labels', []))}]({w['url']}): {w.get('gloss', '')}" if w["found"]
              else (f"no label (page labels: {', '.join(w.get('labels_on_page') or [])[:80]})" if w.get("url") else w.get("reason", "")))
        a, c, r = fmt_gate(g)
        rows.append((st, -(g["ratio"] if g else 0), e["form"], e["sae"], e["type"], wk.replace("|", "/"), a, c, r, (g or {}).get("auth", ""), (g or {}).get("ctrl", "")))
        out.append({"form": e["form"], "sae": e["sae"], "type": e["type"], "status": st.split(" ")[0],
                    "dictionary": w if w["found"] else None, "gate": e.get("gate"), "attestation": e.get("attestation")})
    rows.sort()
    g0 = next((g for e in ev for g in (e.get("gate") or []) if g), None)
    md = [f"# Lexicon: {v.upper()} — {NAMES.get(v, v)}", "",
          "Generated by `exp/tools/lexicon_render.py` from `notes/lexicons/_cache/%s_evidence.json` (items proposed in `_items/%s.tsv`; "
          "evidence by `exp/tools/lexicon_evidence.py`, 2026-09-30). Machine-readable: `notes/lexicons/%s.json`." % (v, v, v), "",
          f"**Gate:** VARIETY = Wiktionary regional label (i) AND authentic/control rate ratio ≥ {RATIO} (ii); ratios trusted only if authentic count ≥ {MIN_COUNT} "
          "(support's addition). SLANG = ratio < 5 (diffuse; feeds INF per the lead). CHECK = one criterion fails but the other is strong; the lead or coder decides. "
          "Counts are whole-word, case-insensitive; rates are per million tokens with +0.5 smoothing. "
          "SLANG requires ≥ 3 control hits; items with ratio < 5 but fewer control hits are CHECK (floor-limited): a small control corpus "
          "cannot certify a 5x ratio for rare items (floor = 5 × 0.5/control_tokens × 10^6 per million).", ""]
    if v in EWAVE:
        md.append(f"eWAVE variety ID for morphosyntax: {EWAVE[v]} (`exp/data_raw/ewave_cldf/`, CC BY 3.0).")
    if g0:
        pairs = sorted({(g["auth"], g["ctrl"], g["auth_tokens"], g["ctrl_tokens"]) for e in ev for g in (e.get("gate") or []) if g})
        md.append("Corpus pairs (authentic → control, tokens): " + "; ".join(
            f"{CORPUS_DESC.get(a, a)} ({na:,}) → {CORPUS_DESC.get(c, c)} ({nc:,}; certifiable authentic rate ≥ {5*0.5/nc*1e6:.0f}/M)" for a, c, na, nc in pairs) + ".")
    else:
        md.append("**No local authentic corpus** for this variety: criterion (ii) cannot be applied; items are dictionary-sourced only (status VARIETY-DICT-ONLY). "
                  "Treat detector precision on authentic text as unvalidated.")
    md += ["", "| status | form | SAE equivalent | type | dictionary evidence (Wiktionary) | authentic count (rate) | control count (rate) | ratio |",
           "|---|---|---|---|---|---|---|---|"]
    for st, _, form, sae, typ, wk, a, c, r, *_ in rows:
        md.append(f"| {st} | {form} | {sae} | {typ} | {wk} | {a} | {c} | {r} |")
    counts = {}
    for r in rows:
        counts[r[0].split(" ")[0]] = counts.get(r[0].split(" ")[0], 0) + 1
    md += ["", "Summary: " + ", ".join(f"{k} {n}" for k, n in sorted(counts.items())) + f" (of {len(rows)})."]
    (LEX / f"{v}.md").write_text("\n".join(md) + "\n")
    (LEX / f"{v}.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
    return counts


if __name__ == "__main__":
    for v in sys.argv[1:]:
        print(v, render(v))
